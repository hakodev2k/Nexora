    await api(page, 'updateShareLink', [link.id, currentLink.etag, 'RestrictedUsers', null, [me.id], true]);
    await editor.getByRole('button', { name: 'Lưu link', exact: true }).click();
    await expect(editor.getByRole('region', { name: 'Phiên bản link hiện tại' })).toContainText('RestrictedUsers');
    await editor.getByRole('button', { name: 'Áp dụng lại bản nháp', exact: true }).click();
    await editor.getByRole('button', { name: 'Lưu link', exact: true }).click(); await expect(editor).toHaveCount(0);
    expect(sql('ShareLink', link.id)[0].Mode).toBe('PublicLink');
    for (let n = 0; n < 29; n++) await api(page, 'createShareLink', ['Project', project.id, 'PublicLink', null, [], true]);
    await page.getByLabel('Resource type filter', { exact: true }).selectOption('Project');
    await page.getByLabel('Resource ID filter', { exact: true }).fill(project.id);
    await page.getByRole('button', { name: 'Lọc links', exact: true }).click();
    await expect(page.locator('.resource-card')).toHaveCount(25);
    await page.getByRole('button', { name: 'Tải thêm links', exact: true }).click(); await expect(page.locator('.resource-card')).toHaveCount(30);
    await expect(page.getByRole('button', { name: 'Tải thêm links', exact: true })).toHaveCount(0);
    await page.getByLabel('Mode filter', { exact: true }).selectOption('AuthenticatedLink');
    await page.getByRole('button', { name: 'Lọc links', exact: true }).click(); await expect(page.locator('.resource-card')).toHaveCount(0);
    await expect(page.getByRole('heading', { name: 'Không có link khớp bộ lọc', exact: true })).toBeVisible();
    await page.getByLabel('Mode filter', { exact: true }).selectOption('PublicLink');
    await page.getByLabel('State filter', { exact: true }).selectOption('Active');
