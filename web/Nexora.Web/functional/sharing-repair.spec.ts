    await page.getByRole('button', { name: 'Xem trước nội dung chia sẻ', exact: true }).click();
    await expect(page.getByRole('region', { name: 'Nội dung sẽ được chia sẻ', exact: true })).toContainText(project.name);
    await page.getByRole('button', { name: 'Tạo read-only link', exact: true }).click();
    const link = await (await created).json();
    await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
    await page.getByRole('button', { name: 'Copy URL', exact: true }).click();
    await expect(page.getByRole('status')).toHaveText('Đã copy URL.');
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(process.env.NEXORA_E2E_BASE_URL + '/share/' + link.token);
    await page.getByRole('button', { name: 'Tải lại', exact: true }).click();
    await expect(page.getByLabel('URL vừa tạo', { exact: true })).toHaveCount(0);
    const card = page.locator('.resource-card').filter({ has: page.getByText(project.id + ' · PublicLink', { exact: true }) });
    await card.getByRole('button', { name: 'Sửa link', exact: true }).click();
    const editor = page.getByRole('dialog', { name: 'Sửa link chia sẻ', exact: true });
    await expect(editor.getByLabel('Audience', { exact: true })).toBeEnabled();
    await editor.getByLabel('Audience', { exact: true }).selectOption('AuthenticatedLink');
    await editor.getByRole('button', { name: 'Hủy', exact: true }).click();
    await editor.getByRole('button', { name: 'Bỏ bản nháp', exact: true }).click();
    expect(sql('ShareLink', link.id)[0].Mode).toBe('PublicLink');
    await card.getByRole('button', { name: 'Sửa link', exact: true }).click();
    await expect(editor.getByLabel('Audience', { exact: true })).toBeEnabled();
    await editor.getByLabel('Audience', { exact: true }).selectOption('AuthenticatedLink');
    await editor.getByRole('button', { name: 'Lưu link', exact: true }).click(); await expect(editor).toHaveCount(0);
    expect(sql('ShareLink', link.id)[0].Mode).toBe('AuthenticatedLink');
    const editedCard = page.locator('.resource-card').filter({ has: page.getByText(project.id + ' · AuthenticatedLink', { exact: true }) });
    await editedCard.getByRole('button', { name: 'Sửa link', exact: true }).click();
    await expect(editor.getByLabel('Audience', { exact: true })).toBeEnabled();
